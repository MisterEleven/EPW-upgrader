@pytest.fixture()
def sample_epw_file(tmp_path: Path) -> Generator[Path, None, None]:
    """Write a minimal but valid EPW file (8 header + 24 data rows) to a temp dir."""
    epw_path = tmp_path / "test.epw"

    lines = _FAKE_HEADER.splitlines(keepends=True)
    assert len(lines) == NUM_HEADER_LINES, (
        f"Fake header has {len(lines)} lines, expected {NUM_HEADER_LINES}"
    )

    with epw_path.open("w", encoding="utf-8") as fh:
        fh.writelines(lines)
        for hour in range(1, 25):
            row = _make_epw_data_row(hour=hour)
            fh.write(",".join(str(v) for v in row) + "\n")

    yield epw_path


